/**
 * 通用的非编码规格管理函数
 * 用于产品创建和编辑页面的规格和指标选择
 */
window.SpecManagement = {

    /**
     * 自动生成产品描述功能模块
     */
    AutoDescription: {
        descriptionField: null,
        autoToggle: null,

        /**
         * 初始化自动生成描述功能
         */
        init: function() {
            this.descriptionField = document.getElementById('description');
            this.autoToggle = document.getElementById('auto-generate-description');

            if (!this.descriptionField || !this.autoToggle) {
                console.log('[AutoDescription] 未找到必需的DOM元素，跳过初始化');
                return;
            }

            console.log('[AutoDescription] 开始初始化');

            // 恢复localStorage状态
            const savedState = localStorage.getItem('productAutoGenerateDescription');
            if (savedState !== null) {
                this.autoToggle.checked = savedState === 'true';
                console.log('[AutoDescription] 从localStorage恢复状态:', this.autoToggle.checked);
            }

            // 绑定事件
            this.bindEvents();

            // 初始生成（仅在新建模式或描述为空时）
            // 编辑模式下如果已有描述内容，不自动生成以避免覆盖
            if (this.autoToggle.checked) {
                const existingDescription = this.descriptionTextarea.value.trim();
                if (!existingDescription) {
                    // 描述为空时才自动生成
                    console.log('[AutoDescription] 描述为空，自动生成');
                    setTimeout(() => this.updateDescription(), 500);
                } else {
                    console.log('[AutoDescription] 编辑模式且已有描述，不自动生成');
                }
            }
        },

        /**
         * 绑定所有事件
         */
        bindEvents: function() {
            // 总开关变化
            this.autoToggle.addEventListener('change', () => {
                const isChecked = this.autoToggle.checked;
                localStorage.setItem('productAutoGenerateDescription', isChecked.toString());
                console.log('[AutoDescription] 总开关变化:', isChecked);

                if (isChecked) {
                    this.updateDescription();
                }
            });

            // 使用事件委托监听规格行的变化
            document.addEventListener('change', (e) => {
                // 规格行的"纳入描述"勾选框变化
                if (e.target.classList.contains('include-in-description')) {
                    console.log('[AutoDescription] 纳入描述勾选框变化');
                    if (this.autoToggle.checked) {
                        this.updateDescription();
                    }
                }

                // 指标选择器变化
                if (e.target.classList.contains('indicator-select')) {
                    console.log('[AutoDescription] 指标选择器变化');
                    if (this.autoToggle.checked) {
                        // 延迟更新，等待隐藏字段更新完成
                        setTimeout(() => this.updateDescription(), 100);
                    }
                }
            });
        },

        /**
         * 收集所有勾选的规格
         * @returns {Array} 规格数组 [{name, value}, ...]
         */
        collectSpecs: function() {
            const specs = [];
            const rows = document.querySelectorAll('#specs-table-body tr');

            rows.forEach(row => {
                const includeCheckbox = row.querySelector('.include-in-description');

                // 检查是否勾选"纳入描述"
                if (!includeCheckbox || !includeCheckbox.checked) {
                    return;
                }

                const specNameInput = row.querySelector('input[name="spec_name[]"]');
                const specValueInput = row.querySelector('input[name="spec_value[]"]');

                if (!specNameInput || !specValueInput) {
                    return;
                }

                const specName = specNameInput.value.trim();
                const indicatorValue = specValueInput.value.trim();

                // 只包含有名称和值的规格
                if (specName && indicatorValue) {
                    // 获取该规格的单位
                    const specFieldUnit = row.dataset.fieldUnit || '';

                    specs.push({
                        name: specName,
                        value: indicatorValue,
                        unit: specFieldUnit
                    });
                }
            });

            console.log('[AutoDescription] 收集到的规格:', specs);
            return specs;
        },

        /**
         * 生成描述文本
         * 格式: 规格名: 指标值, 规格名2: 指标值2
         * @returns {string} 生成的描述文本
         */
        generateDescription: function() {
            const specs = this.collectSpecs();
            const description = specs.map(s => {
                const unit = s.unit ? ` ${s.unit}` : '';
                return `${s.name}: ${s.value}${unit}`;
            }).join(', ');
            console.log('[AutoDescription] 生成的描述:', description);
            return description;
        },

        /**
         * 更新描述字段
         */
        updateDescription: function() {
            if (!this.autoToggle || !this.autoToggle.checked) {
                console.log('[AutoDescription] 总开关未开启，跳过更新');
                return;
            }

            if (!this.descriptionField) {
                console.log('[AutoDescription] 描述字段不存在');
                return;
            }

            const description = this.generateDescription();
            this.descriptionField.value = description;
            console.log('[AutoDescription] 描述已更新');
        }
    },
    
    /**
     * 设置非编码规格行的交互功能
     * @param {HTMLElement} row - 规格行元素
     */
    setupNonCodeSpecRow: function(row) {
        const specSelect = row.querySelector('.spec-select');
        const indicatorSelect = row.querySelector('.indicator-select');
        const specNameHidden = row.querySelector('input[name="spec_name[]"]');
        const specFieldIdHidden = row.querySelector('input[name="spec_field_ids[]"]');
        const indicatorValueHidden = row.querySelector('input[name="spec_value[]"]');
        const indicatorCodeHidden = row.querySelector('input[name="spec_option_codes[]"]');

        // 加载可选的非编码规格
        this.loadNonCodedSpecSelect(row);

        // 规格选择事件
        specSelect.addEventListener('change', () => {
            const specName = specSelect.value;
            specNameHidden.value = specName;
            
            // 获取field_id
            const selectedOption = specSelect.options[specSelect.selectedIndex];
            if (selectedOption && selectedOption.dataset.fieldId) {
                specFieldIdHidden.value = selectedOption.dataset.fieldId;
            }
            
            if (specName) {
                // 启用指标选择框并加载指标选项
                indicatorSelect.disabled = false;
                this.loadIndicatorOptionsForSpec(row, specName, selectedOption.dataset.fieldId);
            } else {
                // 禁用指标选择框
                indicatorSelect.disabled = true;
                indicatorSelect.innerHTML = '<option value="">-- 请先选择规格 --</option>';
                indicatorValueHidden.value = '';
                indicatorCodeHidden.value = '';
                specFieldIdHidden.value = '';
            }
            
            // 更新其他行的可选规格（移除已选择的）
            this.updateAllSpecSelects();
        });

        // 指标选择事件
        indicatorSelect.addEventListener('change', () => {
            const value = indicatorSelect.value;

            // 检测是否选择了"添加新指标"特殊选项
            if (value === '__ADD_NEW_INDICATOR__') {
                // 重置选择框
                indicatorSelect.value = '';

                // 获取当前规格信息
                const specName = specNameHidden.value;
                const specFieldId = specFieldIdHidden.value;

                // 触发快速添加模态框
                if (window.IndicatorQuickAdd) {
                    window.IndicatorQuickAdd.showQuickAddModal(specName, specFieldId, row);
                }
                return;
            }

            const selectedOption = indicatorSelect.options[indicatorSelect.selectedIndex];
            const code = selectedOption.dataset.code || '';

            // 更新隐藏字段
            indicatorValueHidden.value = value;
            indicatorCodeHidden.value = code;
        });
    },

    /**
     * 加载非编码规格到下拉选择框
     * @param {HTMLElement} row - 规格行元素
     */
    loadNonCodedSpecSelect: function(row) {
        const select = row.querySelector('.spec-select');
        const subcategoryId = document.querySelector('input[name="subcategory_id"]')?.value || 
                              document.getElementById('subcategory_id')?.value;
        
        if (!subcategoryId) {
            select.innerHTML = '<option value="">-- 无可用规格 --</option>';
            select.disabled = true;
            return;
        }
        
        // 获取当前已选择的规格名称（包括现有的和新添加的）
        const selectedSpecs = new Set();
        
        // 获取所有已存在的规格名称
        document.querySelectorAll('#specs-table-body tr').forEach(tr => {
            // 检查是否是编码规格或非编码规格
            const specNameInput = tr.querySelector('input[name="spec_name[]"]');
            if (specNameInput && specNameInput.value) {
                selectedSpecs.add(specNameInput.value.trim());
            }
        });
        
        // 获取其他新添加行的选择
        document.querySelectorAll('.spec-select').forEach(sel => {
            if (sel.value && sel !== select) {
                selectedSpecs.add(sel.value);
            }
        });
        
        // 调用API获取该子类别的非编码规格
        fetch(`/product-management/api/subcategory/${subcategoryId}/spec-fields`)
            .then(response => response.json())
            .then(data => {
                select.innerHTML = '<option value="">-- 请选择规格 --</option>';
                
                if (data.spec_fields) {
                    // 只显示非编码规格且未被选择的
                    const availableSpecs = data.spec_fields.filter(field => 
                        !field.use_in_code && !selectedSpecs.has(field.name)
                    );
                    
                    availableSpecs.forEach(field => {
                        const option = document.createElement('option');
                        option.value = field.name;
                        option.textContent = field.name;
                        option.dataset.fieldId = field.id;
                        select.appendChild(option);
                    });
                    
                    // 如果没有可选规格，禁用选择框
                    if (availableSpecs.length === 0) {
                        select.disabled = true;
                        select.innerHTML = '<option value="">没有更多可用的非编码规格</option>';
                    }
                }
            })
            .catch(error => {
                console.error('加载规格选项失败:', error);
                select.innerHTML = '<option value="">加载失败</option>';
                select.disabled = true;
            });
    },

    /**
     * 更新所有规格选择框的选项
     */
    updateAllSpecSelects: function() {
        document.querySelectorAll('.spec-select').forEach(select => {
            // 保存当前选中的值
            const currentValue = select.value;
            if (currentValue) {
                // 如果有选中的值，不重新加载（避免丢失选择）
                return;
            }
            // 重新加载选项
            this.loadNonCodedSpecSelect(select.parentElement.closest('tr'));
        });
        
        // 检查是否还有可添加的规格，决定是否显示添加按钮
        this.checkCanAddMoreSpecs();
    },

    /**
     * 检查是否还能添加更多规格
     */
    checkCanAddMoreSpecs: function() {
        const subcategoryId = document.querySelector('input[name="subcategory_id"]')?.value || 
                              document.getElementById('subcategory_id')?.value;
        if (!subcategoryId) return;
        
        fetch(`/product-management/api/subcategory/${subcategoryId}/spec-fields`)
            .then(response => response.json())
            .then(data => {
                if (!data.spec_fields) return;
                
                // 获取所有已使用的规格名称
                const usedSpecs = new Set();
                document.querySelectorAll('#specs-table-body input[name="spec_name[]"]').forEach(input => {
                    if (input.value) {
                        usedSpecs.add(input.value.trim());
                    }
                });
                
                // 检查是否还有未使用的非编码规格
                const hasAvailableSpecs = data.spec_fields.some(field => 
                    !field.use_in_code && !usedSpecs.has(field.name)
                );
                
                // 控制添加按钮的显示
                const addSpecBtn = document.getElementById('add-spec-btn');
                if (addSpecBtn) {
                    const addSpecContainer = addSpecBtn.closest('div');
                    addSpecContainer.style.display = hasAvailableSpecs ? 'block' : 'none';
                }
            });
    },

    /**
     * 加载指标选项
     * @param {HTMLElement} row - 规格行元素
     * @param {string} specName - 规格名称
     * @param {string} specFieldId - 规格字段ID（可选）
     * @param {string} existingValue - 已保存的指标值（用于编辑模式，可选）
     */
    loadIndicatorOptionsForSpec: function(row, specName, specFieldId = null, existingValue = null) {
        console.log('[DEBUG] loadIndicatorOptionsForSpec 调用 - 规格:', specName, 'field_id:', specFieldId, '已有值:', existingValue);

        const indicatorSelect = row.querySelector('.indicator-select');
        if (!indicatorSelect) {
            console.log('[DEBUG] 未找到指标选择器');
            return;
        }

        const subcategoryId = document.querySelector('input[name="subcategory_id"]')?.value ||
                              document.getElementById('subcategory_id')?.value;
        console.log('[DEBUG] subcategoryId:', subcategoryId);

        // 保存原有的disabled状态
        const wasDisabled = indicatorSelect.disabled;

        // 重置选择框
        indicatorSelect.innerHTML = '<option value="">正在加载...</option>';
        indicatorSelect.disabled = true;

        // 构建API请求URL
        const url = new URL('/product-management/api/spec-field-options', window.location.origin);
        url.searchParams.append('subcategory_id', subcategoryId);
        url.searchParams.append('spec_name', specName);
        if (specFieldId) {
            url.searchParams.append('field_id', specFieldId);
        }
        console.log('[DEBUG] API请求URL:', url.toString());

        // 获取该规格的预定义指标值
        fetch(url)
            .then(response => response.json())
            .then(data => {
                console.log('[DEBUG] API返回数据:', data);
                indicatorSelect.innerHTML = '<option value="">-- 请选择指标值 --</option>';

                // 保存单位到row的dataset
                if (data.field_unit) {
                    row.dataset.fieldUnit = data.field_unit;
                }

                if (data.options && data.options.length > 0) {
                    const fieldUnit = data.field_unit || '';
                    data.options.forEach(opt => {
                        const option = document.createElement('option');
                        option.value = opt.value;
                        const displayUnit = fieldUnit ? ` ${fieldUnit}` : '';
                        option.textContent = `${opt.value}${displayUnit}`;
                        option.dataset.code = opt.code || '';
                        option.dataset.id = opt.id;
                        option.dataset.isActive = opt.is_active !== undefined ? opt.is_active : 'true';
                        indicatorSelect.appendChild(option);
                    });

                    // 添加"快速添加新指标"特殊选项
                    const addNewOption = document.createElement('option');
                    addNewOption.value = '__ADD_NEW_INDICATOR__';
                    addNewOption.textContent = '➕ 添加新指标';
                    addNewOption.style.fontStyle = 'italic';
                    addNewOption.style.color = '#0d6efd';
                    indicatorSelect.appendChild(addNewOption);

                    // 如果有已保存的值，设置为选中
                    if (existingValue) {
                        console.log('[DEBUG] 尝试设置已有值:', existingValue);
                        console.log('[DEBUG] 下拉框选项数量:', indicatorSelect.options.length);

                        // 检查该值是否在选项中
                        let found = false;
                        for (let i = 0; i < indicatorSelect.options.length; i++) {
                            console.log('[DEBUG] 选项', i, '值:', indicatorSelect.options[i].value);
                            if (indicatorSelect.options[i].value === existingValue) {
                                found = true;
                                break;
                            }
                        }
                        console.log('[DEBUG] 已有值是否在选项中:', found);

                        indicatorSelect.value = existingValue;
                        console.log('[DEBUG] 设置后的选中值:', indicatorSelect.value);

                        // 更新隐藏字段
                        const selectedOption = indicatorSelect.options[indicatorSelect.selectedIndex];
                        console.log('[DEBUG] 选中的选项:', selectedOption);
                        if (selectedOption && selectedOption.value) {
                            const valueHidden = row.querySelector('input[name="spec_value[]"]');
                            const codeHidden = row.querySelector('input[name="spec_option_codes[]"]');
                            if (valueHidden) valueHidden.value = existingValue;
                            if (codeHidden) codeHidden.value = selectedOption.dataset.code || '';
                            console.log('[DEBUG] 隐藏字段已更新 - value:', existingValue, 'code:', selectedOption.dataset.code);
                        }
                    }

                    // 恢复原有的disabled状态（如果MN已锁定，保持禁用）
                    indicatorSelect.disabled = wasDisabled;
                    console.log('[DEBUG] 指标选择器disabled状态:', wasDisabled);
                } else {
                    indicatorSelect.innerHTML = '<option value="">该规格暂无预定义指标值</option>';

                    // 即使没有预定义指标，也提供"添加新指标"选项
                    const addNewOption = document.createElement('option');
                    addNewOption.value = '__ADD_NEW_INDICATOR__';
                    addNewOption.textContent = '➕ 添加新指标';
                    addNewOption.style.fontStyle = 'italic';
                    addNewOption.style.color = '#0d6efd';
                    indicatorSelect.appendChild(addNewOption);

                    // 启用选择框，允许用户添加指标
                    indicatorSelect.disabled = false;
                }
            })
            .catch(error => {
                console.error('加载指标选项失败:', error);
                indicatorSelect.innerHTML = '<option value="">加载失败</option>';
                indicatorSelect.disabled = true;
            });
    }
};